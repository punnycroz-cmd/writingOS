/**
 * Writing OS Core — Universal State Model (v5.2 Hardened)
 * Completely register-neutral foundation for persistent entities, facts, claims, and relations.
 * Features:
 * 1. State Authority Hierarchy (CANON > SOURCE_VERIFIED > USER_ASSERTED > OBSERVED > DERIVED > LLM_PROPOSED > UNKNOWN)
 * 2. Anti-State-Contamination Guard (Untrusted proposals cannot overwrite authoritative ground truth)
 * 3. Multi-Hop Graph Traversal & Relational Path Discovery
 * 4. Temporal Relationship & Timeline Consistency Reasoning
 */

export type StateAuthorityLevel = 
  | 'CANON'               // Ground-truth world bible facts (highest authority, rank 6)
  | 'SOURCE_VERIFIED'     // Hard empirical citations / 10-K / lab records (rank 5)
  | 'USER_ASSERTED'       // Explicit user instructions / constraints (rank 4)
  | 'OBSERVED'            // Directly witnessed scene interactions (rank 3)
  | 'DERIVED'             // Proven logical deductions (rank 2)
  | 'LLM_PROPOSED'        // Candidate assertions generated by models (untrusted, rank 1)
  | 'UNKNOWN';            // Epistemically opaque (rank 0)

export const AUTHORITY_RANKS: Record<StateAuthorityLevel, number> = {
  CANON: 6,
  SOURCE_VERIFIED: 5,
  USER_ASSERTED: 4,
  OBSERVED: 3,
  DERIVED: 2,
  LLM_PROPOSED: 1,
  UNKNOWN: 0,
};

export interface ProvenanceRecord {
  sourceId: string;
  sourceType: 'DOCUMENT' | 'USER_PROMPT' | 'CANON_BIBLE' | 'OBSERVATION' | 'PRIOR_REVISION' | 'DEDUCTION' | 'LLM_GENERATION';
  authorityLevel: StateAuthorityLevel;
  locationSnippet?: string;
  timestamp: number;
  confidence: number;
}

export interface PropertyRecord {
  value: unknown;
  authorityLevel: StateAuthorityLevel;
  provenance: ProvenanceRecord[];
  isAuthorized: boolean;
}

export interface BaseEntity {
  id: string;
  entityType: string;
  displayName: string;
  aliases: string[];
  properties: Map<string, PropertyRecord>;
  provenance: ProvenanceRecord[];
  authorizedProperties: Set<string>;
}

export interface BaseClaim {
  id: string;
  subjectId: string;
  predicate: string;
  objectValue: unknown;
  claimType: 'FACT' | 'HYPOTHESIS' | 'OBSERVATION' | 'INFERENCE' | 'PROPOSAL';
  modality?: 'FACTUAL' | 'POSSIBLE' | 'UNCERTAIN' | 'COUNTERFACTUAL';
  isNegated?: boolean;
  authorityLevel: StateAuthorityLevel;
  epistemicStatus: 'CONFIRMED' | 'PROPOSED' | 'DISPUTED' | 'REFUTED' | 'UNKNOWN';
  provenance: ProvenanceRecord[];
  isPrivateSecret?: boolean;
  secretOwnerId?: string;
}

export interface BaseRelation {
  id: string;
  sourceEntityId: string;
  targetEntityId: string;
  relationType: string; // 'OPENS', 'CONTAINS', 'BEFORE', 'AFTER', 'DURING', 'OWNS', 'LOCATED_IN'
  attributes: Record<string, unknown>;
  provenance: ProvenanceRecord[];
}

export interface StateGraphSnapshot {
  timestamp: number;
  entityCount: number;
  claimCount: number;
  relationCount: number;
  unknownCount: number;
  entitiesJson: string;
  claimsJson: string;
  relationsJson: string;
}

export class UniversalStateGraph {
  private entities: Map<string, BaseEntity> = new Map();
  private claims: Map<string, BaseClaim> = new Map();
  private relations: Map<string, BaseRelation> = new Map();
  private unknowns: Set<string> = new Set();
  private revisionHistory: StateGraphSnapshot[] = [];

  constructor() {}

  /**
   * Registers an entity into the state graph with defensive input validation.
   */
  public registerEntity(entity: {
    id: string;
    entityType: string;
    displayName: string;
    aliases?: string[];
    properties?: Record<string, unknown>;
    authorityLevel?: StateAuthorityLevel;
    initialAuthorizedProperties?: string[];
    provenance?: ProvenanceRecord;
  }): BaseEntity {
    if (!entity.id || typeof entity.id !== 'string' || entity.id.trim().length === 0) {
      throw new Error(`StateGraph Error: Entity 'id' must be a non-empty string.`);
    }

    const cleanId = entity.id.trim();
    const existing = this.entities.get(cleanId);
    const authority = entity.authorityLevel || 'CANON';

    if (existing) {
      if (entity.aliases) {
        for (const alias of entity.aliases) {
          if (!existing.aliases.includes(alias)) existing.aliases.push(alias);
        }
      }
      if (entity.properties) {
        for (const [k, v] of Object.entries(entity.properties)) {
          this.setProperty(cleanId, k, v, authority, entity.provenance);
        }
      }
      if (entity.initialAuthorizedProperties) {
        for (const prop of entity.initialAuthorizedProperties) {
          existing.authorizedProperties.add(prop);
        }
      }
      return existing;
    }

    const propMap = new Map<string, PropertyRecord>();
    const authProps = new Set<string>();

    if (entity.initialAuthorizedProperties) {
      for (const prop of entity.initialAuthorizedProperties) {
        authProps.add(prop);
      }
    }

    if (entity.properties) {
      for (const [k, v] of Object.entries(entity.properties)) {
        propMap.set(k, {
          value: v,
          authorityLevel: authority,
          provenance: entity.provenance ? [entity.provenance] : [],
          isAuthorized: authProps.has(k),
        });
      }
    }

    const newEntity: BaseEntity = {
      id: cleanId,
      entityType: entity.entityType || 'GENERAL_ENTITY',
      displayName: entity.displayName || cleanId,
      aliases: entity.aliases || [],
      properties: propMap,
      provenance: entity.provenance ? [entity.provenance] : [],
      authorizedProperties: authProps,
    };

    this.entities.set(cleanId, newEntity);
    return newEntity;
  }

  /**
   * Safe property mutator with strict State Anti-Contamination guard.
   */
  public setProperty(
    entityId: string,
    propertyName: string,
    value: unknown,
    incomingAuthority: StateAuthorityLevel = 'USER_ASSERTED',
    provenance?: ProvenanceRecord
  ): { success: boolean; reason?: string } {
    const entity = this.entities.get(entityId);
    if (!entity) {
      return { success: false, reason: `Entity "${entityId}" not found in state graph.` };
    }

    const existingProp = entity.properties.get(propertyName);
    if (existingProp) {
      const existingRank = AUTHORITY_RANKS[existingProp.authorityLevel] ?? 0;
      const incomingRank = AUTHORITY_RANKS[incomingAuthority] ?? 0;

      if (incomingRank < existingRank) {
        return {
          success: false,
          reason: `STATE_CONTAMINATION_PREVENTED: Cannot overwrite [${existingProp.authorityLevel}] property with lower [${incomingAuthority}] assertion.`,
        };
      }
    }

    const isAuthorized = entity.authorizedProperties.has(propertyName);
    entity.properties.set(propertyName, {
      value,
      authorityLevel: incomingAuthority,
      provenance: provenance ? [provenance] : existingProp ? existingProp.provenance : [],
      isAuthorized,
    });

    return { success: true };
  }

  public authorizeProperty(entityId: string, propertyName: string, evidence?: ProvenanceRecord): boolean {
    const entity = this.entities.get(entityId);
    if (!entity) return false;
    entity.authorizedProperties.add(propertyName);

    const prop = entity.properties.get(propertyName);
    if (prop) {
      prop.isAuthorized = true;
      if (evidence) {
        prop.provenance.push(evidence);
      }
    }

    if (evidence) {
      entity.provenance.push(evidence);
    }
    return true;
  }

  public isPropertyAuthorized(entityId: string, propertyName: string): boolean {
    const entity = this.entities.get(entityId);
    if (!entity) return false;
    return entity.authorizedProperties.has(propertyName);
  }

  public getPropertyValue(entityId: string, propertyName: string): unknown | undefined {
    const entity = this.entities.get(entityId);
    if (!entity) return undefined;
    return entity.properties.get(propertyName)?.value;
  }

  public getPropertyRecord(entityId: string, propertyName: string): PropertyRecord | undefined {
    const entity = this.entities.get(entityId);
    if (!entity) return undefined;
    return entity.properties.get(propertyName);
  }

  public getEntity(id: string): BaseEntity | undefined {
    return this.entities.get(id);
  }

  public getAllEntities(): BaseEntity[] {
    return Array.from(this.entities.values());
  }

  public registerClaim(claim: {
    id: string;
    subjectId: string;
    predicate: string;
    objectValue: unknown;
    claimType?: 'FACT' | 'HYPOTHESIS' | 'OBSERVATION' | 'INFERENCE' | 'PROPOSAL';
    modality?: 'FACTUAL' | 'POSSIBLE' | 'UNCERTAIN' | 'COUNTERFACTUAL';
    isNegated?: boolean;
    authorityLevel?: StateAuthorityLevel;
    epistemicStatus?: 'CONFIRMED' | 'PROPOSED' | 'DISPUTED' | 'REFUTED' | 'UNKNOWN';
    provenance?: ProvenanceRecord;
  }): BaseClaim {
    const cleanId = claim.id || `claim_${Date.now()}_${Math.random().toString(36).substr(2, 6)}`;
    const newClaim: BaseClaim = {
      id: cleanId,
      subjectId: claim.subjectId,
      predicate: claim.predicate,
      objectValue: claim.objectValue,
      claimType: claim.claimType || 'FACT',
      modality: claim.modality || 'FACTUAL',
      isNegated: claim.isNegated ?? false,
      authorityLevel: claim.authorityLevel || 'CANON',
      epistemicStatus: claim.epistemicStatus || 'CONFIRMED',
      provenance: claim.provenance ? [claim.provenance] : [],
      isPrivateSecret: (claim as any).isPrivateSecret,
      secretOwnerId: (claim as any).secretOwnerId,
    };
    this.claims.set(cleanId, newClaim);
    return newClaim;
  }

  public getAllClaims(): BaseClaim[] {
    return Array.from(this.claims.values());
  }

  public getClaimsForEntity(subjectId: string): BaseClaim[] {
    return Array.from(this.claims.values()).filter(c => c.subjectId === subjectId);
  }

  public registerRelation(relation: {
    id?: string;
    sourceEntityId: string;
    targetEntityId: string;
    relationType: string;
    attributes?: Record<string, unknown>;
    provenance?: ProvenanceRecord;
  }): BaseRelation {
    const cleanId = relation.id || `rel_${relation.sourceEntityId}_${relation.relationType}_${relation.targetEntityId}`;
    const newRelation: BaseRelation = {
      id: cleanId,
      sourceEntityId: relation.sourceEntityId,
      targetEntityId: relation.targetEntityId,
      relationType: relation.relationType.toUpperCase(),
      attributes: relation.attributes || {},
      provenance: relation.provenance ? [relation.provenance] : [],
    };
    this.relations.set(cleanId, newRelation);
    return newRelation;
  }

  public getAllRelations(): BaseRelation[] {
    return Array.from(this.relations.values());
  }

  /**
   * Multi-hop path search between entities across directed relations.
   */
  public findRelationPath(sourceEntityId: string, targetEntityId: string, maxHops = 4): BaseRelation[] | null {
    if (sourceEntityId === targetEntityId) return [];

    const queue: { currentId: string; path: BaseRelation[] }[] = [{ currentId: sourceEntityId, path: [] }];
    const visited = new Set<string>([sourceEntityId]);

    while (queue.length > 0) {
      const { currentId, path } = queue.shift()!;
      if (path.length >= maxHops) continue;

      const outgoing = Array.from(this.relations.values()).filter(r => r.sourceEntityId === currentId);
      for (const rel of outgoing) {
        if (rel.targetEntityId === targetEntityId) {
          return [...path, rel];
        }
        if (!visited.has(rel.targetEntityId)) {
          visited.add(rel.targetEntityId);
          queue.push({ currentId: rel.targetEntityId, path: [...path, rel] });
        }
      }
    }

    return null;
  }

  /**
   * Evaluates temporal order consistency.
   * Returns true if eventA is deterministically proven to occur BEFORE eventB.
   */
  public isChronologicallyBefore(eventAId: string, eventBId: string): boolean {
    const path = this.findRelationPath(eventAId, eventBId);
    if (!path) return false;
    return path.every(rel => rel.relationType === 'BEFORE' || rel.relationType === 'PRECEDES');
  }

  public addUnknown(unknownItem: string): void {
    this.unknowns.add(unknownItem);
  }

  public isUnknown(item: string): boolean {
    return this.unknowns.has(item);
  }

  public getUnknowns(): string[] {
    return Array.from(this.unknowns);
  }

  public captureSnapshot(): StateGraphSnapshot {
    const entitiesObj: Record<string, unknown> = {};
    for (const [id, entity] of this.entities.entries()) {
      const props: Record<string, unknown> = {};
      for (const [k, v] of entity.properties.entries()) {
        props[k] = v;
      }
      entitiesObj[id] = {
        ...entity,
        properties: props,
        authorizedProperties: Array.from(entity.authorizedProperties),
      };
    }

    const snapshot: StateGraphSnapshot = {
      timestamp: Date.now(),
      entityCount: this.entities.size,
      claimCount: this.claims.size,
      relationCount: this.relations.size,
      unknownCount: this.unknowns.size,
      entitiesJson: JSON.stringify(entitiesObj),
      claimsJson: JSON.stringify(Array.from(this.claims.values())),
      relationsJson: JSON.stringify(Array.from(this.relations.values())),
    };
    this.revisionHistory.push(snapshot);
    return snapshot;
  }

  /**
   * Complete rollback to a prior snapshot. Guarantees 0 residual state mutation.
   */
  public rollbackToSnapshot(snapshot: StateGraphSnapshot): boolean {
    try {
      this.entities.clear();
      this.claims.clear();
      this.relations.clear();

      const parsedEntities = JSON.parse(snapshot.entitiesJson);
      for (const [id, e] of Object.entries(parsedEntities as Record<string, any>)) {
        const propMap = new Map<string, PropertyRecord>();
        for (const [k, v] of Object.entries(e.properties as Record<string, PropertyRecord>)) {
          propMap.set(k, v);
        }
        this.entities.set(id, {
          id: e.id,
          entityType: e.entityType,
          displayName: e.displayName,
          aliases: e.aliases || [],
          properties: propMap,
          provenance: e.provenance || [],
          authorizedProperties: new Set(e.authorizedProperties || []),
        });
      }

      const parsedClaims = JSON.parse(snapshot.claimsJson);
      for (const c of parsedClaims as BaseClaim[]) {
        this.claims.set(c.id, c);
      }

      const parsedRelations = JSON.parse(snapshot.relationsJson);
      for (const r of parsedRelations as BaseRelation[]) {
        this.relations.set(r.id, r);
      }

      return true;
    } catch {
      return false;
    }
  }
}
